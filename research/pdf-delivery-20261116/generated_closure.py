"""Audit locked producer outputs, including upstream undeclared byproducts.

No invented headers, compiler flag changes or alternate generator. Incomplete
old checkpoints are rejected before restoration; original Ninja generates all.
"""
import hashlib
from pathlib import Path
import re
import shlex

SOURCE = {
    'Source/JavaScriptCore/b3/air/opcode_generator.rb': 'c0a3106fdde6cc905f4238e15e99fd1e4b813d2a87ea01198458baa49bfd47db',
    'Source/JavaScriptCore/b3/air/AirOpcode.opcodes': '7cce5357cdc1301af7c43b26f504e822d337a640405b579568d3f9de8ed2b7c4',
    'Source/JavaScriptCore/CMakeLists.txt': '750e70beabfa6c7e5c1f4016567a8aa26a3d37a7cbb22fdc99c7d9b247031ac8',
}
PRODUCTS = ['JavaScriptCore/DerivedSources/Air' + name + '.h'
            for name in ['Opcode', 'OpcodeUtils', 'OpcodeGenerated']]


def audit(source, build):
    for name, expected in SOURCE.items():
        assert hashlib.sha256((source / name).read_bytes()).hexdigest() == expected, 'Generator source drift'
    script = source / next(iter(SOURCE))
    outputs = re.findall(r'^writeH\("([A-Za-z]+)"\) \{', script.read_text(), re.M)
    assert outputs == ['Opcode', 'OpcodeUtils', 'OpcodeGenerated']
    blocks = [b for b in (build / 'build.ninja').read_text().split('\n\n')
              if b.startswith('build ' + PRODUCTS[0] + ' ')]
    assert len(blocks) == 1, 'Exact upstream producer edge required'
    block = blocks[0]; command = next(l.split(' = ', 1)[1] for l in block.splitlines() if l.startswith('  COMMAND = '))
    expected = ['cd', str(build / 'JavaScriptCore/DerivedSources'), '&&', '/usr/bin/ruby',
                str(script), str(source / 'Source/JavaScriptCore/b3/air/AirOpcode.opcodes')]
    assert shlex.split(command) == expected, 'Original generator command changed'
    declared = block.splitlines()[0].split(': CUSTOM_COMMAND ', 1)[0].split(' | ', 1)[0].split()[1:]
    assert declared == [PRODUCTS[0], PRODUCTS[2]], 'Re-review upstream byproduct registration'
    return {'sourceHashes': SOURCE, 'command': command, 'declaredOutputs': declared,
            'actualOutputs': PRODUCTS, 'undeclaredOutputs': [PRODUCTS[1]]}


def missing(manifest, products=PRODUCTS):
    return [name for name in products
            if manifest['records'].get(name, {}).get('kind') != 'generated'
            or 'build/' + name not in manifest['files']]


def completed(build, products=PRODUCTS):
    present = [(build / name).exists() for name in products]
    if not any(present):
        return []  # Producer has not executed; never invent a completed output.
    assert all(present), 'Partially generated producer output set cannot be checkpointed'
    for name in products:
        p = build / name
        assert p.is_file() and not p.is_symlink() and 0 < p.stat().st_size < 4 * 1024**2
        assert p.read_bytes().startswith(b'// Generated by opcode_generator.rb from AirOpcode.opcodes -- do not edit!\n')
    return list(products)
