import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';
import os from 'node:os';
const evidence=path.dirname(fileURLToPath(import.meta.url));
const moduleFile=path.resolve(process.argv[2]??'/workspace/milkup-mermaid-rebuild/tests/windows/mermaid-product-e2e.mjs');
const report=JSON.parse(await readFile(path.join(evidence,'installed/mermaid-product-e2e.json'),'utf8'));
const lf=await readFile(moduleFile);
const windows=Buffer.from(lf.toString('utf8').replace(/\r?\n/g,'\r\n'));
assert.equal(createHash('sha256').update(windows).digest('hex'),report.harnessSha256,'Reconstructed CRLF checkout equals executed harness bytes');
const temporary=await mkdtemp(path.join(os.tmpdir(),'mermaid-audit-replay-'));
const exactModule=path.join(temporary,'exact-harness.mjs');
await writeFile(exactModule,windows);
const {AuditLedger}=await import(pathToFileURL(exactModule).href);
const ledger=new AuditLedger(report.context.expectedSid);
for(const event of report.nativeAudit)ledger.accept(event,event.productPid);
const jobs=ledger.verifyAll();
for(const launch of report.launches)assert.equal(ledger.pending(launch.productPid),0);
const result={status:'passed',candidateSha:report.candidateSha,harnessSha256:report.harnessSha256,events:report.nativeAudit.length,jobs:jobs.length,allFinished:true,moduleReconstruction:'Local LF checkout converted to Windows CRLF; exact report harness SHA matched before import',scope:'Replay of exact executed harness AuditLedger over retained original native records; no product execution'};
await writeFile(path.join(evidence,'native-ledger-replay.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));

await rm(temporary,{recursive:true,force:true});
